CREATE TABLE llx_mjlfinancement_expense (
 rowid BIGINT AUTO_INCREMENT PRIMARY KEY,
 entity INT NOT NULL,
 fk_operation BIGINT NOT NULL,
 kind VARCHAR(16) NOT NULL DEFAULT 'EXPENSE',
 label VARCHAR(255) NOT NULL,
 expense_date DATE NOT NULL,
 amount BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 fk_original BIGINT DEFAULT NULL,
 reason TEXT DEFAULT NULL,
 contributors LONGTEXT NOT NULL,
 fk_author INT NOT NULL,
 fk_reviewer INT DEFAULT NULL,
 decision_reason TEXT DEFAULT NULL,
 date_creation DATETIME NOT NULL,
 date_submitted DATETIME DEFAULT NULL,
 date_decided DATETIME DEFAULT NULL,
 version BIGINT NOT NULL DEFAULT 1,
 pending_original BIGINT GENERATED ALWAYS AS (CASE WHEN status IN ('DRAFT','SUBMITTED') THEN fk_original ELSE NULL END) STORED,
 reversed_original BIGINT GENERATED ALWAYS AS (CASE WHEN kind='REVERSAL' THEN fk_original ELSE NULL END) STORED,
 UNIQUE KEY uk_mjl_expense_entity (entity,rowid),
 UNIQUE KEY uk_mjl_expense_pending (entity,pending_original),
 UNIQUE KEY uk_mjl_expense_reversal (entity,reversed_original),
 KEY idx_mjl_expense_operation (entity,fk_operation,status),
 CONSTRAINT fk_mjl_expense_operation FOREIGN KEY (entity,fk_operation) REFERENCES llx_mjlfinancement_operation(entity,rowid),
 CONSTRAINT fk_mjl_expense_original FOREIGN KEY (entity,fk_original) REFERENCES llx_mjlfinancement_expense(entity,rowid),
 CONSTRAINT fk_mjl_expense_author FOREIGN KEY (fk_author) REFERENCES llx_user(rowid),
 CONSTRAINT fk_mjl_expense_reviewer FOREIGN KEY (fk_reviewer) REFERENCES llx_user(rowid),
 CONSTRAINT chk_mjl_expense_entity CHECK (entity>0 AND version>0),
 CONSTRAINT chk_mjl_expense_label CHECK (label REGEXP '[^[:space:]]'),
 CONSTRAINT chk_mjl_expense_status CHECK (status IN ('DRAFT','SUBMITTED','APPROVED','REJECTED','WITHDRAWN')),
 CONSTRAINT chk_mjl_expense_kind CHECK ((kind='EXPENSE' AND amount>=0) OR (kind='REVERSAL' AND amount<=0 AND status='APPROVED' AND fk_original IS NOT NULL)),
 CONSTRAINT chk_mjl_expense_correction CHECK (fk_original IS NULL OR (reason IS NOT NULL AND reason REGEXP '[^[:space:]]')),
 CONSTRAINT chk_mjl_expense_contributors CHECK (JSON_VALID(contributors) AND JSON_TYPE(contributors)='ARRAY' AND JSON_LENGTH(contributors)>0),
 CONSTRAINT chk_mjl_expense_decision CHECK ((status IN ('APPROVED','REJECTED') AND fk_reviewer IS NOT NULL AND date_decided IS NOT NULL AND NOT JSON_CONTAINS(contributors,CAST(fk_reviewer AS CHAR))) OR (status NOT IN ('APPROVED','REJECTED') AND fk_reviewer IS NULL AND date_decided IS NULL)),
 CONSTRAINT chk_mjl_expense_submitted CHECK (status IN ('DRAFT','WITHDRAWN') OR date_submitted IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_uca1400_ai_ci;
